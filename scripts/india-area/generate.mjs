// Builds the India administrative area data (state -> district -> sub-district) from the
// Local Government Directory (LGD) open-data snapshots at https://ramseraph.github.io/opendata/lgd/
//
// Usage: copy this file into an empty folder, then from that folder:
//   npm i hyparquet@1.13.1 hyparquet-compressors@1.1.1
//   node generate.mjs <repoRoot>
//
// Writes:
//   server/tenanthub-service/src/main/resources/db/changelog/sql/india_area.sql
//   platform-web-ui/src/assets/IndiaArea.json
//   tenant-web-ui/src/assets/IndiaArea.json
//
// Area codes encode the hierarchy so they are unique across levels and the parent is derivable:
//   areaCode = state * 1e9 + district * 1e5 + subdistrict   (LGD codes; 0 for levels not present)
import { parquetReadObjects } from "hyparquet"
import { compressors } from "hyparquet-compressors"
import { createHash } from "node:crypto"
import fs from "node:fs"
import path from "node:path"

const root = process.argv[2]
if (!root) throw new Error("usage: node generate.mjs <repoRoot>")

const BASE = "https://ramseraph.github.io/opendata/lgd/data/"
const metadata = await (await fetch(BASE + "metadata.json")).json()

async function load(key) {
  const entry = metadata.datasets[key]
  const { url, sha256 } = entry.daily.file
  const buf = Buffer.from(await (await fetch(url)).arrayBuffer())
  const actual = createHash("sha256").update(buf).digest("hex")
  if (actual !== sha256) throw new Error(`${key}: checksum mismatch`)
  const rows = await parquetReadObjects({ file: buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength), compressors })
  console.log(`${key}: ${rows.length} rows, observed ${entry.daily.observed_on}`)
  return { rows, observedOn: entry.daily.observed_on }
}

// "Jammu And Kashmir" -> "Jammu and Kashmir"; "MAUGANJ" -> "Mauganj"
const tidy = (name) => {
  let n = name.trim().replace(/\s+/g, " ")
  if (n === n.toUpperCase() && /[A-Z]{3}/.test(n)) n = n.toLowerCase().replace(/\b\w/g, (c) => c.toUpperCase())
  return n.replace(/ (And|Of) /g, (m) => m.toLowerCase())
}

const code = (s = 0, d = 0, t = 0) => Number(s) * 1e9 + Number(d) * 1e5 + Number(t)
const byName = (a, b) => a.name.localeCompare(b.name, "en")

const states = await load("states")
const districts = await load("districts")
const subdistricts = await load("subdistricts")

const tree = states.rows
  .map((s) => ({
    areaCode: code(s.state_code),
    name: tidy(s.state_name),
    parentCode: 0,
    lgdCode: Number(s.state_code),
    level: 1,
    type: s.state_or_ut === "U" ? "UT" : "State"
  }))
  .sort(byName)
const stateByLgd = new Map(tree.map((s) => [s.lgdCode, s]))

const districtByLgd = new Map()
for (const d of districts.rows) {
  const state = stateByLgd.get(Number(d.state_code))
  const node = {
    areaCode: code(d.state_code, d.district_code),
    name: tidy(d.district_name),
    parentCode: state.areaCode,
    lgdCode: Number(d.district_code),
    level: 2
  }
  ;(state.children ??= []).push(node)
  districtByLgd.set(node.lgdCode, { node, state })
}
for (const t of subdistricts.rows) {
  const { node: district } = districtByLgd.get(Number(t.district_code))
  ;(district.children ??= []).push({
    areaCode: code(t.state_code, t.district_code, t.subdistrict_code),
    name: tidy(t.subdistrict_name),
    parentCode: district.areaCode,
    lgdCode: Number(t.subdistrict_code),
    level: 3
  })
}

// mergerName = "State-District-Subdistrict", used for display
const flat = []
const walk = (nodes, prefix) => {
  nodes.sort(byName)
  for (const n of nodes) {
    n.mergerName = prefix ? `${prefix}-${n.name}` : n.name
    flat.push(n)
    if (n.children) walk(n.children, n.mergerName)
  }
}
walk(tree, "")

// Frontend cascader data (only the fields the UI uses)
const slim = (nodes) =>
  nodes.map((n) => ({
    areaCode: n.areaCode,
    name: n.name,
    parentCode: n.parentCode,
    mergerName: n.mergerName,
    ...(n.children ? { children: slim(n.children) } : {})
  }))
const json = JSON.stringify(slim(tree))
for (const app of ["platform-web-ui", "tenant-web-ui"]) {
  fs.writeFileSync(path.join(root, app, "src/assets/IndiaArea.json"), json + "\n")
}

// Liquibase seed
const q = (s) => `'${String(s).replace(/'/g, "''")}'`
const lines = [
  "-- India administrative areas (state -> district -> sub-district).",
  `-- Source: Local Government Directory (LGD), Ministry of Panchayati Raj, via https://ramseraph.github.io/opendata/lgd/`,
  `-- Snapshot: states ${states.observedOn}, districts ${districts.observedOn}, sub-districts ${subdistricts.observedOn}`,
  "-- Generated by scripts/india-area/generate.mjs. Do not edit by hand.",
  ""
]
for (let i = 0; i < flat.length; i += 500) {
  const values = flat
    .slice(i, i + 500)
    .map((n) => `(${n.areaCode}, ${n.level}, ${n.parentCode}, ${n.lgdCode}, ${q(n.name)}, ${q(n.mergerName)}, ${q(n.type ?? "")})`)
  lines.push(
    "INSERT INTO `india_area` (`area_code`, `level`, `parent_code`, `lgd_code`, `name`, `merger_name`, `type`) VALUES\n" +
      values.join(",\n") +
      ";"
  )
}
fs.writeFileSync(path.join(root, "server/tenanthub-service/src/main/resources/db/changelog/sql/india_area.sql"), lines.join("\n") + "\n")
console.log(`wrote ${flat.length} areas (${tree.length} states/UTs)`)
